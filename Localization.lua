local locale = GetLocale and GetLocale() or "enUS"
local aliases = { enGB = "enUS", esMX = "esES" }
local sourceLocale = aliases[locale] or locale
local translated = dictionaries[sourceLocale] or {}
ns.Locale = locale
ns.IsEnglish = dictionaries[sourceLocale] == nil
ns.ReadyLabelWidth = ({ frFR = 126, ptBR = 126, itIT = 116, koKR = 100, zhCN = 100, zhTW = 100 })[sourceLocale] or 112
local L
L = setmetatable({}, { __index = function(self, key)
    local value = translated[key]
    if not value and type(key) == "string" then
        local number = key:match("^(%d+) px$")
        if number then value = string.format(L["%d px"], tonumber(number)) end
        number = key:match("^(%d+) seconds?$")
        if number then value = string.format(L[tonumber(number) == 1 and "%d second" or "%d seconds"], tonumber(number)) end
    end
    value = value or key
    rawset(self, key, value)
    return value
end })
ns.L = L
ns.Localization = { locale = locale, sourceLocale = sourceLocale, dictionaries = dictionaries }
